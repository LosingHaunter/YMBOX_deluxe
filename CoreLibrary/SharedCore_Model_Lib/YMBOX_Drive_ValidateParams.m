function report = YMBOX_Drive_ValidateParams( ...
        cfg, sampleTime_s, throwOnError, resolvedParameters)
%YMBOX_DRIVE_VALIDATEPARAMS Validate the unified production parameter path.

arguments
    cfg (1,1) struct = YMBOX_Drive_Parameters()
    sampleTime_s (1,1) double = NaN
    throwOnError (1,1) logical = true
    resolvedParameters (1,1) struct = struct()
end
if isnan(sampleTime_s)
    defaultTiming = YMBOX_Timing_Resolve();
    sampleTime_s = defaultTiming.ControlPeriod_s;
end

errors = strings(0,1);
warnings = strings(0,1);

if isempty(fieldnames(resolvedParameters))
    try
        prm = YMBOX_Drive_CalculateParams(cfg, sampleTime_s);
    catch exception
        errors(end+1,1) = string(exception.message);
        prm = struct();
    end
else
    prm = resolvedParameters;
end

if isempty(errors)
    % Validate physical domains here before publishing unrestricted data
    % objects. These checks mirror calculator inputs, not motor-size caps.
    positivePaths = { ...
        'Limits.SoftwareOverCurrent_A', 'Limits.SoftwareOverCurrentConfirm_s', ...
        'Limits.SpeedCommandAbsMax_rpm', 'Observer.EffectiveResistanceScale', ...
        'Observer.EffectiveInductance_H', 'Inverter.CurrentSignBoundaryMin_A', ...
        'StartupSupervisor.DirectHandoverTime_s'};
    nonnegativePaths = { ...
        'Motor.ViscousFriction_Nms', 'CurrentSensor.NoiseStd_A', ...
        'Inverter.HighSideVoltageDrop_V', 'Inverter.LowSideVoltageDrop_V', ...
        'Inverter.CurrentSignNoiseMultiplier', 'Inverter.CurrentSignHold_s', ...
        'Inverter.NonlinearityCompensationGain', 'Inverter.NonlinearityCompensationMax_V', ...
        'ControlTargets.SpeedCommandSlew_rpms', ...
        'FieldWeakening.VoltageLoopKp_AperUnit', ...
        'FieldWeakening.VoltageLoopKi_AperUnitPerS', 'FieldWeakening.IdSlew_Aps', ...
        'StartupSupervisor.IfAccelBlendTime_s', 'StartupSupervisor.IfAlignTime_s', ...
        'StartupSupervisor.IfBlendTime_s'};
    for path = [positivePaths nonnegativePaths]
        parts = strsplit(path{1}, '.'); value = cfg.(parts{1}).(parts{2});
        strictlyPositive = ismember(path, positivePaths);
        if ~isfinite(value) || value < 0 || (strictlyPositive && value == 0)
            errors(end+1,1) = string(path{1}) + " violates its physical domain.";
        end
    end
    if cfg.Motor.PolePairs ~= fix(cfg.Motor.PolePairs) || ...
            cfg.Motor.PolePairs > double(intmax('uint16'))
        errors(end+1,1) = "Pole pairs must fit the published uint16 type.";
    end
    if round(cfg.Limits.SoftwareOverCurrentConfirm_s/sampleTime_s) > double(intmax('uint8'))
        errors(end+1,1) = "Software over-current confirmation exceeds the uint8 counter capacity.";
    end
    if round(cfg.Inverter.CurrentSignHold_s/sampleTime_s) > double(intmax('uint16'))
        errors(end+1,1) = "Current-sign hold time exceeds the uint16 counter capacity.";
    end
    if ~ismember(cfg.Inverter.DeadTimePolarity, [-1 1]) || ...
            cfg.Inverter.LinearModulationUtilization_NULL <= 0 || ...
            cfg.Inverter.LinearModulationUtilization_NULL > 1
        errors(end+1,1) = "Invalid dead-time polarity or linear-modulation utilization.";
    end
    if cfg.FieldWeakening.EntryUtilization_NULL > 1 || ...
            cfg.FieldWeakening.ExitUtilization_NULL < 0
        errors(end+1,1) = "Weakening utilization must satisfy 0 <= exit < entry <= 1.";
    end
    startupCurrents = [prm.Observer.IfStartIq_A, prm.Observer.IfAlignId_A, ...
        prm.Observer.DirectAccelIqSeed_A];
    if any(~isfinite(startupCurrents)) || any(startupCurrents < 0) || ...
            any(startupCurrents > min(cfg.Motor.MaxCurrent_A, cfg.Limits.CurrentCommandMax_A))
        errors(end+1,1) = "Startup currents must remain within motor and command current limits.";
    end
    if ~isfinite(prm.Observer.IfIqSlew_Aps) || prm.Observer.IfIqSlew_Aps <= 0
        errors(end+1,1) = "Startup current slew must be finite and positive.";
    end
    % The model compares squared current directly in single precision.
    % A finite calibration alone does not guarantee a finite square.
    currentSquares = single([prm.Constraint.CurrentMax_A, ...
        prm.Constraint.SoftwareOverCurrent_A]).^2;
    if any(~isfinite(currentSquares)) || any(currentSquares == 0)
        errors(end+1,1) = ...
            "Configured current limits must have finite positive single-precision squares.";
    end
    if ~isscalar(cfg.Feedforward.VoltageMode_enum) || ...
            ~ismember(double(cfg.Feedforward.VoltageMode_enum), 0:3)
        errors(end+1,1) = "Voltage feedforward mode must be 0, 1, 2 or 3.";
    end
    if ~isscalar(cfg.Feedforward.ElectricalAngleCompEnable) || ...
            ~ismember(double(cfg.Feedforward.ElectricalAngleCompEnable), [0 1])
        errors(end+1,1) = "Electrical angle compensation enable must be boolean.";
    end
    versions = {cfg.Meta.ProfileVersion, cfg.Meta.SchemaVersion};
    for index = 1:numel(versions)
        value = versions{index};
        if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
                ~isfinite(value) || value < 0
            errors(end+1,1) = ...
                "ProfileVersion and SchemaVersion must be finite nonnegative numbers.";
        end
    end
    mdtmDivider = double(cfg.Timing.MDTMTaskDivider_NULL);
    if ~isscalar(mdtmDivider) || ~isfinite(mdtmDivider) || ...
            mdtmDivider ~= fix(mdtmDivider) || mdtmDivider < 1 || ...
            mdtmDivider > double(intmax('uint16'))
        errors(end+1,1) = ...
            "MDTM task divider must be a positive uint16 integer.";
    end
    motorClass = upper(string(cfg.Meta.MotorClass));
    if ~ismember(motorClass, ["SPMSM", "IPMSM"])
        errors(end+1,1) = ...
            "MotorClass must be SPMSM or IPMSM.";
    end
    if motorClass == "SPMSM" && ...
            prm.Motor.SaliencyRatio_NULL > ...
            cfg.CurrentReference.MinimumIpmsmSaliencyRatio_NULL
        errors(end+1,1) = sprintf( ...
            "SPMSM Ld/Lq saliency %.3f exceeds the limit %.3f.", ...
            prm.Motor.SaliencyRatio_NULL, ...
            cfg.CurrentReference.MinimumIpmsmSaliencyRatio_NULL);
    end
    if motorClass == "IPMSM"
        if cfg.Motor.Lq_H <= cfg.Motor.Ld_H
            errors(end+1,1) = ...
                "IPMSM MTPA requires Lq > Ld > 0.";
        end
        if prm.Motor.SaliencyRatio_NULL <= ...
                cfg.CurrentReference.MinimumIpmsmSaliencyRatio_NULL
            errors(end+1,1) = sprintf( ...
                "IPMSM saliency %.3f must exceed %.3f.", ...
                prm.Motor.SaliencyRatio_NULL, ...
                cfg.CurrentReference.MinimumIpmsmSaliencyRatio_NULL);
        end
    end
    if cfg.Motor.Ld_H <= 0 || cfg.Motor.Lq_H <= 0 || ...
            cfg.Motor.PmFlux_Wb <= 0 || cfg.Motor.PolePairs <= 0
        errors(end+1,1) = ...
            "Motor Ld, Lq, PM flux, and pole pairs must be positive.";
    end
    if cfg.Motor.RatedCurrent_A <= 0 || cfg.Motor.MaxCurrent_A <= 0 || ...
            cfg.Motor.RatedCurrent_A > cfg.Motor.MaxCurrent_A
        errors(end+1,1) = ...
            "Motor currents must satisfy 0 < rated current <= maximum current.";
    end
    if cfg.Limits.CurrentCommandMax_A <= 0 || ...
            cfg.Limits.CurrentCommandMax_A > cfg.Motor.MaxCurrent_A
        errors(end+1,1) = ...
            "Current command maximum must be positive and no greater than " + ...
            "the motor maximum current.";
    end
    tableSize = double(cfg.CurrentReference.MtpaTableSize);
    if ~isfinite(tableSize) || tableSize ~= fix(tableSize) || ...
            tableSize < 17 || tableSize > 257
        errors(end+1,1) = ...
            "MTPA table size must be an integer in [17, 257].";
    end
    if ~isequal(uint16(cfg.CurrentReference.AllocationModes_enum(:).'), ...
            uint16([4 5 17]))
        errors(end+1,1) = ...
            "Motor-current allocation modes must be uint16([4 5 17]).";
    end
    if cfg.Inverter.MinDuty_NULL < 0 || ...
            cfg.Inverter.MaxDuty_NULL > 1 || ...
            cfg.Inverter.MinDuty_NULL >= cfg.Inverter.MaxDuty_NULL
        errors(end+1,1) = ...
            "Inverter duty limits must satisfy 0 <= min < max <= 1.";
    end
    if ~isfinite(cfg.Inverter.DeadTime_s) || ...
            cfg.Inverter.DeadTime_s < 0
        errors(end+1,1) = ...
            "Inverter dead time must be finite and non-negative.";
    end
    if ~isfinite(cfg.Inverter.MaximumDeadTimeDuty_NULL) || ...
            cfg.Inverter.MaximumDeadTimeDuty_NULL <= 0 || ...
            cfg.Inverter.MaximumDeadTimeDuty_NULL >= 0.5
        errors(end+1,1) = ...
            "Maximum dead-time duty must be in the interval (0, 0.5).";
    elseif cfg.Inverter.DeadTime_s*prm.PwmFrequency_Hz > ...
            cfg.Inverter.MaximumDeadTimeDuty_NULL
        errors(end+1,1) = ...
            "Inverter dead time exceeds the configured PWM-duty limit.";
    end
    dcBusFilterAlpha_NULL = single([ ...
        cfg.DcBusMeasurement.VoltageControlFilterAlpha_NULL
        cfg.DcBusMeasurement.VoltageReportFilterAlpha_NULL]);
    if any(~isfinite(dcBusFilterAlpha_NULL)) || ...
            any(dcBusFilterAlpha_NULL <= single(0)) || ...
            any(dcBusFilterAlpha_NULL > single(1))
        errors(end+1,1) = ...
            "DC-bus filter Alpha values must be finite and in (0, 1].";
    end
    if cfg.DcBusMeasurement.VoltageReportFilterAlpha_NULL > ...
            cfg.DcBusMeasurement.VoltageControlFilterAlpha_NULL
        errors(end+1,1) = ...
            "DC-bus report Alpha must not exceed the control Alpha.";
    end
    currentAverageWindow = single( ...
        cfg.DcBusMeasurement.CurrentInputMovingAverageWindowSamples);
    if ~isfinite(currentAverageWindow) || ...
            currentAverageWindow ~= fix(currentAverageWindow) || ...
            currentAverageWindow < single(1) || ...
            currentAverageWindow > single(64)
        errors(end+1,1) = ...
            "DC-bus current moving-average window must be an integer in [1, 64].";
    end
    if ~ismember(uint8(cfg.DcBusMeasurement.CurrentSource_enum), uint8([0 1]))
        errors(end+1,1) = ...
            "DC-bus current source must be 0 (physical) or 1 (estimated).";
    end
    dcBusPlausibleMin_V = single( ...
        cfg.DcBusMeasurement.VoltagePlausibleMin_V);
    dcBusPlausibleMaxFactor_NULL = single( ...
        cfg.DcBusMeasurement.VoltagePlausibleMaxFactor_NULL);
    dcBusPlausibleMax_V = dcBusPlausibleMaxFactor_NULL * ...
        single(cfg.Inverter.MaxDcBus_V);
    dcBusInitMin_V = single(cfg.Inverter.MinValidDcBus_V);
    if ~isfinite(dcBusPlausibleMin_V) || ...
            dcBusPlausibleMin_V < single(0) || ...
            ~isfinite(dcBusPlausibleMaxFactor_NULL) || ...
            dcBusPlausibleMaxFactor_NULL <= single(1) || ...
            ~isfinite(dcBusPlausibleMax_V) || ...
            dcBusPlausibleMin_V >= dcBusPlausibleMax_V
        errors(end+1,1) = ...
            "DC-bus voltage plausibility settings are invalid.";
    end
    if ~isfinite(dcBusInitMin_V) || ...
            dcBusInitMin_V <= dcBusPlausibleMin_V || ...
            dcBusInitMin_V >= dcBusPlausibleMax_V
        errors(end+1,1) = ...
            "DC-bus initialization minimum must lie strictly inside the plausibility range.";
    end
    if ~isfinite(cfg.DcBusMeasurement.CurrentPlausibleMax_A) || ...
            cfg.DcBusMeasurement.CurrentPlausibleMax_A <= 0 || ...
            ~isfinite(cfg.DcBusMeasurement.CurrentHardMax_A) || ...
            ~isfinite(cfg.DcBusMeasurement.CurrentHardMin_A) || ...
            cfg.DcBusMeasurement.CurrentHardMin_A >= 0 || ...
            cfg.DcBusMeasurement.CurrentHardMax_A <= 0 || ...
            cfg.DcBusMeasurement.CurrentHardMin_A >= ...
            cfg.DcBusMeasurement.CurrentHardMax_A || ...
            max(abs([cfg.DcBusMeasurement.CurrentHardMin_A, ...
            cfg.DcBusMeasurement.CurrentHardMax_A])) > ...
            cfg.DcBusMeasurement.CurrentPlausibleMax_A
        errors(end+1,1) = ...
            "DC-bus current hard limits must lie inside the plausibility range.";
    end
    if ~isfinite(cfg.Simulation.PowerStageStep_s) || ...
            cfg.Simulation.PowerStageStep_s <= 0
        errors(end+1,1) = ...
            "Simulation power-stage step must be finite and positive.";
    elseif cfg.Simulation.PowerStageStep_s > 1/prm.PwmFrequency_Hz
        errors(end+1,1) = ...
            "Simulation power-stage step must not exceed one PWM period.";
    end
    if prm.Simulation.PwmDeadTimeSteps_NULL > ...
            double(intmax('uint16'))
        errors(end+1,1) = ...
            "Simulated PWM dead time exceeds the uint16 delay range.";
    end
    if cfg.Limits.VoltageMargin_NULL <= 0 || ...
            cfg.Limits.VoltageMargin_NULL > 1
        errors(end+1,1) = ...
            "Voltage margin must be in the interval (0, 1].";
    end
    currentPiGains = [ ...
        cfg.ControlTargets.CurrentLoopKpD_VperA
        cfg.ControlTargets.CurrentLoopKpQ_VperA
        cfg.ControlTargets.CurrentLoopKiSeriesD_perS
        cfg.ControlTargets.CurrentLoopKiSeriesQ_perS
        cfg.ControlTargets.CurrentLoopKc_perS];
    if any(~isfinite(currentPiGains)) || any(currentPiGains <= 0)
        errors(end+1,1) = ...
            "Manual current-PI Kp, Ki, and Kc values must be finite and positive.";
    end
    speedPiGains = [ ...
        cfg.ControlTargets.SpeedLoopKp_AperRpm
        cfg.ControlTargets.SpeedLoopKiSeriesPerStep_NULL
        cfg.ControlTargets.SpeedLoopKcSeriesPerStep_NULL];
    if any(~isfinite(speedPiGains)) || any(speedPiGains <= 0)
        errors(end+1,1) = ...
            "Manual speed-PI Kp, KiStep, and KcStep values must be finite and positive.";
    end
    if cfg.FieldWeakening.ExitUtilization_NULL >= ...
            cfg.FieldWeakening.EntryUtilization_NULL
        errors(end+1,1) = ...
            "Field-weakening exit utilization must be below entry.";
    end
    if prm.FieldWeakening.IdMin_A > 0
        errors(end+1,1) = ...
            "Field-weakening Id minimum must be non-positive.";
    end
    if ~ismember(cfg.PositionSensor.ControlAngleCounts, [4096 8192])
        errors(end+1,1) = ...
            "ControlAngleCounts must be 4096 or 8192; " + ...
            "the board SinCos LUT uses the same full-turn resolution.";
    end
    nativeCounts = double(cfg.PositionSensor. ...
        NativeCountsPerMechanicalRev);
    nativeBits = log2(nativeCounts);
    if ~isfinite(nativeCounts) || nativeCounts ~= fix(nativeCounts) || ...
            nativeBits ~= fix(nativeBits) || ...
            nativeBits < 12 || nativeBits > 24
        errors(end+1,1) = ...
            "Native position counts must be a power of two from 12 to 24 bits.";
    end
    if isfield(cfg.PositionSensor, 'PllBandwidth_rads') && ...
            (~isfinite(cfg.PositionSensor.PllBandwidth_rads) || ...
            cfg.PositionSensor.PllBandwidth_rads <= 0)
        errors(end+1,1) = ...
            "Position PLL bandwidth must be finite and positive.";
    end
    if ~ismember(cfg.PositionSensor.Direction, [-1, 1])
        errors(end+1,1) = ...
            "Position sensor direction must be +1 or -1.";
    end
    % Predictor/corrector error dynamics have trace 2-2q-q^2 and
    % determinant 1-2q, q = bandwidth*Ts. Jury requires q < sqrt(8)-2.
    if cfg.PositionSensor.PllBandwidth_rads * sampleTime_s >= sqrt(8)-2
        errors(end+1,1) = ...
            "Position PLL bandwidth exceeds the discrete stability limit; " + ...
            "require bandwidth*controlPeriod < sqrt(8)-2.";
    end
    math = cfg.PlatformMath;
    trigBackends = ["LUT","GENERIC","TRICORE","TI_TMU","STM32_CORDIC"];
    if ~ismember(string(math.SinCosBackend),trigBackends) || ...
            ~ismember(string(math.AtanBackend),trigBackends) || ...
            ~ismember(string(math.SqrtBackend),["GENERIC","TI_TMU","STM32_FPU"])
        errors(end+1,1) = "Unsupported board math implementation.";
    end
    selections = string({math.SinCosBackend,math.AtanBackend,math.SqrtBackend});
    families = [any(startsWith(selections,"STM32_")), ...
        any(selections=="TI_TMU"),any(selections=="TRICORE")];
    if nnz(families)>1
        errors(end+1,1) = "Board math implementations cannot mix STM32, TI and TriCore targets.";
    end
    if motorClass == "IPMSM" && isempty(errors)
        publishedBreakpoints = single(prm.CurrentReference.EquivalentIqBreakpoints_A);
        if any(~isfinite(publishedBreakpoints)) || any(diff(publishedBreakpoints) <= 0)
            errors(end+1,1) = ...
                "MTPA breakpoints must remain finite and strictly increasing in single precision.";
        end
        if any(diff(prm.CurrentReference.TorqueBreakpoints_Nm) <= 0)
            errors(end+1,1) = ...
                "IPMSM MTPA torque breakpoints must be strictly increasing.";
        end
        if any(hypot(prm.CurrentReference.IdTable_A, ...
                prm.CurrentReference.IqTable_A) > ...
                prm.CurrentReference.MaximumCurrent_A + 1e-9)
            errors(end+1,1) = ...
                "IPMSM MTPA table exceeds the configured current limit.";
        end
        warnings(end+1,1) = ...
            "IPMSM extended-EMF SMO has documented nominal 4-kHz MIL " + ...
            "coverage; qualify each new envelope and the target hardware.";
    end
    if ~prm.Simulation.PwmPeriodExactlyRepresentable_flg
        warnings(end+1,1) = string(sprintf([ ...
            'PWM period is not an integer multiple of the %.9g s ' ...
            'simulation base tick; carrier edges are resolved by the ' ...
            'fixed-step plant at the nearest solver instant.'], ...
            cfg.Simulation.PowerStageStep_s));
    end
    if cfg.Limits.SoftwareOverCurrent_A < ...
            cfg.Limits.CurrentCommandMax_A
        warnings(end+1,1) = string(sprintf([ ...
            'Software over-current %.3g A is below command limit %.3g A. ' ...
            'This legacy calibration is preserved for safety and must be ' ...
            'reconciled against real current scaling before release.'], ...
            cfg.Limits.SoftwareOverCurrent_A, ...
            cfg.Limits.CurrentCommandMax_A));
    end
    if cfg.Features.ActiveInverterCompensationEnable && ...
            prm.Inverter.NominalPhaseError_V <= 0
        warnings(end+1,1) = ...
            "Active inverter compensation is enabled with zero voltage error.";
    end
    if prm.Simulation.PwmDeadTimeQuantizationError_s > ...
            100*eps(max(1, cfg.Inverter.DeadTime_s))
        warnings(end+1,1) = string(sprintf([ ...
            'PWM dead time %.9g s is quantized upward to %.9g s by the ' ...
            '%.9g s switching-plant step.'], ...
            cfg.Inverter.DeadTime_s, ...
            prm.Simulation.PwmDeadTimeEffective_s, ...
            cfg.Simulation.PowerStageStep_s));
    end
    if cfg.Features.SensorlessFieldWeakeningEnable
        warnings(end+1,1) = ...
            "Sensorless field weakening is enabled without the separate " + ...
            "high-speed observer release gate.";
    end
end

report.ProfileName = string(cfg.Meta.ProfileName);
report.ProfileVersion = cfg.Meta.ProfileVersion;
report.SampleTime_s = sampleTime_s;
report.Errors = errors;
report.Warnings = warnings;
report.ErrorCount = uint16(numel(errors));
report.WarningCount = uint16(numel(warnings));
report.Passed = isempty(errors);
report.Derived = prm;

if throwOnError && ~report.Passed
    error('YMBOX:Drive:InvalidProfile', '%s', ...
        strjoin(cellstr(report.Errors), newline));
end
end
