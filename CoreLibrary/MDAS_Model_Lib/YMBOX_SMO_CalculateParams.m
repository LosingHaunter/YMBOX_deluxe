function prm = YMBOX_SMO_CalculateParams(cfg, sampleTime_s)
%YMBOX_SMO_CALCULATEPARAMS Calculate the complete generic SMO parameter path.
%   PRM contains both physics-based recommendations and the final applied
%   values after identified overrides.  Time-based supervision settings are
%   converted to counts using SAMPLETIME_S, so the same profile supports
%   different generated-code rates.

arguments
    cfg (1,1) struct
    sampleTime_s (1,1) double {mustBeFinite, mustBePositive}
end

m = cfg.MotorPhysical;
inv = cfg.InverterAndSensing;
smo = cfg.SmoIdentified;
sup = cfg.Supervisor;

% Reject retired profile fields instead of silently ignoring an old override.
retiredMotorFields = {'StatorResistance20_Ohm', ...
    'CopperTempCoefficient_perC', 'WindingTemperature_C'};
if any(isfield(m, retiredMotorFields))
    error('YMBOX:SMO:RetiredResistanceFields', ...
        ['Set MotorPhysical.StatorResistance_Ohm directly; ', ...
        'static winding-temperature fields are no longer supported.']);
end

validatePositive(m.PolePairs, 'MotorPhysical.PolePairs');
validatePositive(m.StatorResistance_Ohm, ...
    'MotorPhysical.StatorResistance_Ohm');
validatePositive(m.Ld_H, 'MotorPhysical.Ld_H');
validatePositive(m.Lq_H, 'MotorPhysical.Lq_H');
validatePositive(m.PmFlux_Wb, 'MotorPhysical.PmFlux_Wb');
validatePositive(m.MaxCurrent_A, 'MotorPhysical.MaxCurrent_A');
validatePositive(inv.NominalDcBus_V, ...
    'InverterAndSensing.NominalDcBus_V');
validatePositive(smo.EmfLpfPole_rads, ...
    'SmoIdentified.EmfLpfPole_rads');
validatePositive(smo.PllBandwidth_rads, ...
    'SmoIdentified.PllBandwidth_rads');
validatePositive(smo.PllDamping, 'SmoIdentified.PllDamping');
validatePositive(sup.IfAccel_rpms, 'Supervisor.IfAccel_rpms');

prm.SampleTime_s = sampleTime_s;
if isfinite(inv.PwmFrequencyOverride_Hz)
    prm.PwmFrequency_Hz = inv.PwmFrequencyOverride_Hz;
else
    prm.PwmFrequency_Hz = 1/sampleTime_s;
end
validatePositive(prm.PwmFrequency_Hz, ...
    'InverterAndSensing.PwmFrequencyOverride_Hz');

% Layer 1 -> operating motor model.
prm.PolePairs = m.PolePairs;
prm.OperatingStatorResistance_Ohm = m.StatorResistance_Ohm;
validatePositive(prm.OperatingStatorResistance_Ohm, ...
    'calculated operating stator resistance');
prm.AverageInductance_H = 0.5*(m.Ld_H + m.Lq_H);
prm.SaliencyRatio = abs(m.Lq_H - m.Ld_H) / ...
    max(prm.AverageInductance_H, eps);
prm.RequiresExtendedEmfModel = prm.SaliencyRatio > 0.25;
prm.TorqueConstant_NmPerA = 1.5*m.PolePairs*m.PmFlux_Wb;
prm.MaxElecSpeedCalculated_rads = m.MaxMechSpeed_rpm * ...
    (2*pi/60)*m.PolePairs;
prm.MaxElecSpeed_rads = chooseOverride( ...
    prm.MaxElecSpeedCalculated_rads, smo.MaxElecSpeedOverride_rads);

% Layer 2 -> inverter voltage reconstruction and dead-time model.
prm.NominalDcBus_V = inv.NominalDcBus_V;
prm.MinValidDcBus_V = inv.MinValidDcBus_V;
prm.MaxDcBus_V = inv.MaxDcBus_V;
prm.DeadTimeDutyFraction = min(0.10, max(0, ...
    inv.DeadTime_s*prm.PwmFrequency_Hz));
prm.DeviceVoltageDrop_V = max(0, inv.DeviceVoltageDrop_V);
prm.DeadTimeCompEnable = double(logical(inv.DeadTimeCompEnable));
prm.DeadTimePolarity = sign(inv.DeadTimePolarity);
if prm.DeadTimePolarity == 0
    prm.DeadTimePolarity = 1;
end
prm.DeadTimeCurrentBoundary_A = max( ...
    inv.CurrentSignBoundaryMin_A, ...
    inv.CurrentSignNoiseMultiplier*inv.CurrentNoiseStd_A);
prm.NominalDeadTimeError_V = ...
    prm.NominalDcBus_V*prm.DeadTimeDutyFraction + ...
    prm.DeviceVoltageDrop_V;

% Layer 3 -> identified current model, sliding injection, EMF LPF, and PLL.
prm.ModelResistance_Ohm = prm.OperatingStatorResistance_Ohm * ...
    smo.EffectiveResistanceScale;
% The IPMSM extended-EMF identity uses Ld in the scalar predictor and
% (Ld-Lq)*omega*J*i in the voltage input. This selects the physical model;
% observer tuning values are still supplied by the manual profile.
prm.ExtendedEmfEnabled = isfield(cfg, 'MotorClass') && ...
    strcmpi(cfg.MotorClass, 'IPMSM');
prm.SaliencyInductance_H = 0;
if prm.ExtendedEmfEnabled
    prm.ModelInductance_H = m.Ld_H;
    prm.SaliencyInductance_H = m.Ld_H-m.Lq_H;
elseif isfinite(smo.EffectiveInductance_H)
    prm.ModelInductance_H = smo.EffectiveInductance_H;
else
    prm.ModelInductance_H = prm.AverageInductance_H;
end
validatePositive(prm.ModelResistance_Ohm, ...
    'calculated SMO model resistance');
validatePositive(prm.ModelInductance_H, ...
    'calculated SMO model inductance');

prm.CurrentNormalizedStep = prm.ModelResistance_Ohm / ...
    prm.ModelInductance_H*sampleTime_s;
prm.CurrentEulerA = 1-prm.CurrentNormalizedStep;
prm.CurrentEulerB_AperV = sampleTime_s/prm.ModelInductance_H;
prm.CurrentEulerStable = ...
    prm.CurrentNormalizedStep > 0 && prm.CurrentNormalizedStep < 2;
prm.CurrentEulerMonotonic = prm.CurrentNormalizedStep <= 1;
prm.CurrentZohA = exp(-prm.CurrentNormalizedStep);
prm.CurrentZohB_AperV = (1-prm.CurrentZohA) / ...
    prm.ModelResistance_Ohm;
prm.CurrentEulerPoleError_pct = 100*abs( ...
    prm.CurrentEulerA-prm.CurrentZohA)/prm.CurrentZohA;
prm.CurrentEulerInputGainError_pct = 100*( ...
    prm.CurrentEulerB_AperV-prm.CurrentZohB_AperV) / ...
    prm.CurrentZohB_AperV;
prm.EmfLpfPole_rads = smo.EmfLpfPole_rads;
prm.EmfLpfA = exp(-prm.EmfLpfPole_rads*sampleTime_s);
prm.EmfLpfB = 1-prm.EmfLpfA;
prm.PllBandwidth_rads = smo.PllBandwidth_rads;
prm.PllKp = 2*smo.PllDamping*prm.PllBandwidth_rads;
prm.PllKiTs = prm.PllBandwidth_rads^2*sampleTime_s;
% Match the published single-precision PLL gains once at initialization.
prm.PllSpeedLpfAlpha = 1-exp(-single(prm.PllKiTs)/single(prm.PllKp));
prm.MinEmf_V = smo.MinEmf_V;

designElecSpeed = smo.DesignMechSpeed_rpm * ...
    (2*pi/60)*m.PolePairs;
prm.DesignBackEmf_V = designElecSpeed*m.PmFlux_Wb;
resistanceMismatch_V = smo.ResistanceUncertaintyFraction * ...
    prm.ModelResistance_Ohm*m.MaxCurrent_A;
inductanceMismatch_V = smo.InductanceUncertaintyFraction * ...
    prm.ModelInductance_H*inv.CurrentSlew_Aps;
prm.SlideGainCalculated_V = smo.SlideGainMargin * ...
    (prm.DesignBackEmf_V + resistanceMismatch_V + ...
    inductanceMismatch_V + inv.VoltageErrorBudget_V);
prm.SlideGain_V = chooseOverride( ...
    prm.SlideGainCalculated_V, smo.SlideGainOverride_V);

prm.ErrBoundaryCalculated_A = max([ ...
    inv.CurrentSignNoiseMultiplier*inv.CurrentNoiseStd_A, ...
    smo.ErrBoundaryRatedFraction*m.RatedCurrent_A, ...
    1e-3]);
prm.ErrBoundary_A = chooseOverride( ...
    prm.ErrBoundaryCalculated_A, smo.ErrBoundaryOverride_A);

prm.EmfObservableSpeed_rpm = 60/(2*pi*m.PolePairs) * ...
    (smo.EmfObservabilityMargin*prm.MinEmf_V/m.PmFlux_Wb);
prm.SwitchSpeedCalculated_rpm = max( ...
    smo.MinSwitchSpeed_rpm, prm.EmfObservableSpeed_rpm);
prm.SwitchSpeed_rpm = chooseOverride( ...
    prm.SwitchSpeedCalculated_rpm, smo.SwitchSpeedOverride_rpm);
switchElecSpeed = prm.SwitchSpeed_rpm * ...
    (2*pi/60)*m.PolePairs;
switchBackEmf_V = switchElecSpeed*m.PmFlux_Wb;

% Production eSMO injection schedule. The fixed-gain values above remain
% available for traceability and form the safe fallback when adaptation is
% disabled. Scheduling is deliberately bounded, rate independent, and
% driven by one-sample-delayed filtered back-EMF in the model.
prm.AdaptiveInjectionEnable = double(logical( ...
    smo.AdaptiveInjectionEnable));
slideGainMinCalculated_V = prm.SlideGain_V;
slideGainMaxCalculated_V = max( ...
    prm.SlideGainCalculated_V, slideGainMinCalculated_V);
boundaryMaxCalculated_A = prm.ErrBoundary_A;
boundaryMinCalculated_A = max( ...
    prm.ErrBoundaryCalculated_A, 0.70*boundaryMaxCalculated_A);
scheduleEmfLowCalculated_V = max( ...
    prm.MinEmf_V, 0.40*switchBackEmf_V);
scheduleEmfHighCalculated_V = max( ...
    scheduleEmfLowCalculated_V + prm.MinEmf_V, ...
    prm.DesignBackEmf_V);

prm.SlideGainMin_V = chooseOverride( ...
    slideGainMinCalculated_V, smo.SlideGainMinOverride_V);
prm.SlideGainMax_V = chooseOverride( ...
    slideGainMaxCalculated_V, smo.SlideGainMaxOverride_V);
prm.ErrBoundaryMin_A = chooseOverride( ...
    boundaryMinCalculated_A, smo.ErrBoundaryMinOverride_A);
prm.ErrBoundaryMax_A = chooseOverride( ...
    boundaryMaxCalculated_A, smo.ErrBoundaryMaxOverride_A);
prm.GainScheduleEmfLow_V = chooseOverride( ...
    scheduleEmfLowCalculated_V, ...
    smo.GainScheduleEmfLowOverride_V);
prm.GainScheduleEmfHigh_V = chooseOverride( ...
    scheduleEmfHighCalculated_V, ...
    smo.GainScheduleEmfHighOverride_V);
validatePositive(smo.GainScheduleTimeConstant_s, ...
    'SmoIdentified.GainScheduleTimeConstant_s');

if ~logical(smo.AdaptiveInjectionEnable)
    prm.SlideGainMin_V = prm.SlideGain_V;
    prm.SlideGainMax_V = prm.SlideGain_V;
    prm.ErrBoundaryMin_A = prm.ErrBoundary_A;
    prm.ErrBoundaryMax_A = prm.ErrBoundary_A;
end

validatePositive(prm.SlideGainMin_V, ...
    'calculated adaptive minimum slide gain');
validatePositive(prm.SlideGainMax_V, ...
    'calculated adaptive maximum slide gain');
validatePositive(prm.ErrBoundaryMin_A, ...
    'calculated adaptive minimum error boundary');
validatePositive(prm.ErrBoundaryMax_A, ...
    'calculated adaptive maximum error boundary');
validatePositive(prm.GainScheduleEmfLow_V, ...
    'calculated adaptive low EMF breakpoint');
validatePositive(prm.GainScheduleEmfHigh_V, ...
    'calculated adaptive high EMF breakpoint');
if prm.SlideGainMax_V < prm.SlideGainMin_V
    error('YMBOX:SMO:InvalidAdaptiveGainRange', ...
        'Adaptive slide-gain maximum must be >= minimum.');
end
if prm.ErrBoundaryMax_A < prm.ErrBoundaryMin_A
    error('YMBOX:SMO:InvalidAdaptiveBoundaryRange', ...
        'Adaptive error-boundary maximum must be >= minimum.');
end
if prm.GainScheduleEmfHigh_V <= prm.GainScheduleEmfLow_V
    error('YMBOX:SMO:InvalidAdaptiveEmfRange', ...
        'Adaptive EMF high breakpoint must be > low breakpoint.');
end

prm.SlideGainSpan_V = ...
    prm.SlideGainMax_V-prm.SlideGainMin_V;
prm.ErrBoundarySpan_A = ...
    prm.ErrBoundaryMax_A-prm.ErrBoundaryMin_A;
prm.GainScheduleEmfSpanInv_PerV = 1 / ...
    (prm.GainScheduleEmfHigh_V-prm.GainScheduleEmfLow_V);
prm.GainScheduleTimeConstant_s = ...
    smo.GainScheduleTimeConstant_s;
prm.GainScheduleAlpha = 1-exp( ...
    -sampleTime_s/prm.GainScheduleTimeConstant_s);
if ~(isscalar(smo.GainScheduleAngleComp_rad) && ...
        isfinite(smo.GainScheduleAngleComp_rad))
    error('YMBOX:SMO:InvalidAdaptiveAngleCompensation', ...
        'Adaptive angle compensation must be a finite scalar.');
end
prm.GainScheduleAngleComp_rad = ...
    smo.GainScheduleAngleComp_rad;
if ~logical(smo.AdaptiveInjectionEnable)
    prm.GainScheduleAngleComp_rad = 0;
end

prm.ReadySpeedErrorCalculated_rads = max(1, ...
    smo.ReadySpeedErrorFraction*switchElecSpeed);
prm.ReadySpeedError_rads = chooseOverride( ...
    prm.ReadySpeedErrorCalculated_rads, ...
    smo.ReadySpeedErrorOverride_rads);
prm.ReadyPllError = smo.ReadyPllError;
prm.StaticAngleOffset_rad = smo.StaticAngleOffset_rad;
prm.TotalDelay_s = smo.TotalDelay_s + inv.SamplingDelay_s;

% Layer 4 -> startup torque, handover timing, and state-machine counts.
prm.IfAccel_rpms = sup.IfAccel_rpms;
prm.IfAccelBlendTime_s = sup.IfAccelBlendTime_s;
prm.IfAlignTime_s = sup.IfAlignTime_s;
prm.IfBlendTime_s = sup.IfBlendTime_s;
prm.IfSwitchSpeed_rpm = sup.IfSwitchSpeed_rpm;
prm.DirectHandoverTime_s = sup.DirectHandoverTime_s;
prm.ObserverExitRatio = sup.ObserverExitRatio;

mechanicalAccel = sup.IfAccel_rpms*2*pi/60;
switchMechanicalSpeed = prm.SwitchSpeed_rpm*2*pi/60;
accelTorque = m.Inertia_kgm2*mechanicalAccel + ...
    m.ViscousFriction_Nms*switchMechanicalSpeed + ...
    abs(m.LoadTorque_Nm);
prm.DirectAccelIqSeedCalculated_A = accelTorque / ...
    max(prm.TorqueConstant_NmPerA, eps);
prm.DirectAccelIqSeed_A = chooseOverride( ...
    prm.DirectAccelIqSeedCalculated_A, ...
    sup.DirectAccelIqSeedOverride_A);
prm.IfStartIqCalculated_A = max( ...
    prm.DirectAccelIqSeedCalculated_A, ...
    abs(m.LoadTorque_Nm)/max(prm.TorqueConstant_NmPerA, eps));
prm.IfStartIq_A = chooseOverride( ...
    prm.IfStartIqCalculated_A, sup.IfStartIqOverride_A);
prm.IfAlignId_A = chooseOverride( ...
    min(0.15*m.RatedCurrent_A, m.MaxCurrent_A), ...
    sup.IfAlignIdOverride_A);
prm.IfIqSlew_Aps = chooseOverride( ...
    10*prm.IfStartIq_A, sup.IfIqSlewOverride_Aps);
prm.HandoverCurrentLpfTau_s = sup.HandoverCurrentLpfTau_s;
prm.HandoverCurrentLpfAlpha = 1-exp( ...
    -sampleTime_s/prm.HandoverCurrentLpfTau_s);

startupCalculated = sup.IfAlignTime_s + sup.IfBlendTime_s + ...
    prm.SwitchSpeed_rpm/sup.IfAccel_rpms + ...
    sup.SmoReadyConfirmTime_s + sup.StartupTimeoutMargin_s;
prm.StartupTimeoutCalculated_s = startupCalculated;
prm.StartupTimeout_s = chooseOverride( ...
    startupCalculated, sup.StartupTimeoutOverride_s);
prm.SmoReadyConfirmCount = timeToCount( ...
    sup.SmoReadyConfirmTime_s, sampleTime_s, 'uint16');
prm.ObserverLossConfirmCount = timeToCount( ...
    sup.ObserverLossConfirmTime_s, sampleTime_s, 'uint32');
prm.DirectHandoverDwellCount = timeToCount( ...
    sup.DirectHandoverDwellTime_s, sampleTime_s, 'uint32');
prm.StartupTimeoutCount = timeToCount( ...
    prm.StartupTimeout_s, sampleTime_s, 'uint32');

prm.Trace.CurrentModel = ...
    'a=exp(-Rmodel/Lmodel*Ts), b=(1-a)/Rmodel';
prm.Trace.CurrentModelEuler = ...
    'aFE=1-Rmodel/Lmodel*Ts, bFE=Ts/Lmodel';
prm.Trace.DeadTime = ...
    'Verr=(Vdc*Tdead*Fpwm+Vdrop)*sat(I/Iboundary)';
prm.Trace.SlideGain = ...
    'Kslide=margin*(Edesign+dR*Imax+dL*di/dt+Verror)';
prm.Trace.AdaptiveInjection = ...
    ['rho=LPF(sat((|Ehat|z1-Elow)/(Ehigh-Elow))); ' ...
    'Kslide=Kmin+(Kmax-Kmin)*rho; ' ...
    'boundary=Bmax-(Bmax-Bmin)*rho; ' ...
    'thetaComp=thetaCompFS*rho'];
prm.Trace.SwitchSpeed = ...
    'nsw=max(nmin,60/(2*pi*p)*Emargin*Emin/psiPM)';
prm.Trace.Pll = ...
    'Kp=2*zeta*bandwidth, KiTs=bandwidth^2*Ts';
prm.Trace.Angle = ...
    'theta=thetaPLL+atan(omega/omegaLPF)+omega*Tdelay+theta0';
end

function output = chooseOverride(calculated, override)
if isfinite(override)
    output = override;
else
    output = calculated;
end
end

function count = timeToCount(time_s, sampleTime_s, dataType)
validatePositive(time_s, 'supervisor time');
countValue = max(1, round(time_s/sampleTime_s));
maximumCount = double(intmax(dataType));
if countValue > maximumCount
    error('YMBOX:SMO:CountOverflow', ...
        ['Supervisor time %.12g s at Ts %.12g s requires %.0f counts, ' ...
        'which exceeds %s.'], ...
        time_s, sampleTime_s, countValue, dataType);
end
count = cast(countValue, dataType);
end

function validatePositive(value, name)
if ~(isscalar(value) && isfinite(value) && value > 0)
    error('YMBOX:SMO:InvalidParameter', '%s must be positive.', name);
end
end
