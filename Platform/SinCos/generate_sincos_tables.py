"""Generate the two supported quarter-wave SinCos tables (no runtime setup)."""
from pathlib import Path
import math


def main():
    destination = Path(__file__).resolve().parent
    for counts in (4096, 8192):
        segments = counts // 4
        values = [f"{math.sin(math.pi * index / (2 * segments)):.9g}"
                  for index in range(segments + 1)]
        values = [value + (".0" if "." not in value and "e" not in value else "") + "F"
                  for value in values]
        lines = ["/* Generated by generate_sincos_tables.py; do not edit. */"]
        lines += ["    " + ", ".join(values[index:index + 6]) + ","
                  for index in range(0, len(values), 6)]
        (destination / f"mdsa_sincos_quarter_{counts}.inc").write_text(
            "\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
