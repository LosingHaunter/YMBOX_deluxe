function [cfg, resolvedPaths] = YMBOX_Configuration_Decode(document, options)
%YMBOX_Configuration_Decode - Decode and validate a tool configuration
%   CFG = YMBOX_Configuration_Decode(DOCUMENT) accepts a JSON filename or
%   a configuration struct. It rejects unknown fields, restores MATLAB
%   data types, and resolves legacy JSON null to the model's numeric value.
%
%   See Also YMBOX_Drive_ResolveProfile, YMBOX_ImportConfiguration

arguments
    document
    options.AllowUnreleasedControlFrequency (1,1) logical = false
end

if ischar(document) || isstring(document)
    document = YMBOX_Configuration_ReadFile(document);
end
assert(isstruct(document) && isscalar(document), ...
    'YMBOX:Configuration:InvalidDocument', 'Configuration must be an object.');
if isfield(document, 'drive')
    assert(isfield(document, 'schemaVersion') && document.schemaVersion == 1 && ...
        isfield(document, 'kind') && strcmp(document.kind, 'YMBOXConfiguration'), ...
        'YMBOX:Configuration:SchemaVersion', 'Unsupported configuration schema.');
    document = document.drive;
end
% Migrate old documents before enforcing the current field catalog.
document = YMBOX_Drive_MigrateProfile(document);
defaults = YMBOX_Drive_Parameters();
cfg = decodeFields(defaults, document, '');
[cfg, resolvedPaths] = YMBOX_Configuration_ResolveAuto(cfg, ...
    AllowUnreleasedControlFrequency= ...
    options.AllowUnreleasedControlFrequency);
fixedTiming = {'BaseTick_s', 'MinimumControlFrequency_Hz', ...
    'MaximumControlFrequency_Hz', ...
    'ExactMatchTolerance_ppm'};
for index = 1:numel(fixedTiming)
    name = fixedTiming{index};
    assert(isequal(cfg.Timing.(name), defaults.Timing.(name)), ...
        'YMBOX:Configuration:FixedTimingConstraint', ...
        'Timing.%s is fixed at %.12g by the current model.', ...
        name, defaults.Timing.(name));
end
frequency = double(cfg.Timing.ControlFrequency_Hz);
[cfg, derived] = YMBOX_Drive_ResolveProfile(1/frequency, cfg, ...
    AllowUnreleasedControlFrequency= ...
    options.AllowUnreleasedControlFrequency);
YMBOX_Drive_ValidateParams(cfg, 1/frequency, true, derived);
YMBOX_SMO_ResolveDriveProfile(1/frequency, cfg);
validateExecution(cfg);
end

function output = decodeFields(template, inputValues, prefix)
assert(isstruct(inputValues) && isscalar(inputValues), ...
    'YMBOX:Configuration:InvalidGroup', '%s must be an object.', prefix);
expected = fieldnames(template);
actual = fieldnames(inputValues);
assert(isempty(setdiff(actual, expected)), ...
    'YMBOX:Configuration:UnknownField', 'Unknown field under %s.', prefix);
assert(isempty(setdiff(expected, actual)), ...
    'YMBOX:Configuration:MissingField', 'Missing configuration field under %s.', prefix);
output = template;
for index = 1:numel(expected)
    key = expected{index};
    name = [prefix key];
    value = inputValues.(key);
    original = template.(key);
    if isstruct(original)
        output.(key) = decodeFields(original, value, [name '.']);
    elseif ischar(original)
        assert((ischar(value) && isrow(value)) || (isstring(value) && isscalar(value)), ...
            'YMBOX:Configuration:InvalidText', '%s must be text.', name);
        output.(key) = char(value);
    elseif islogical(original)
        assert(isscalar(value) && (islogical(value) || isnumeric(value)) && ...
            ismember(double(value), [0 1]), ...
            'YMBOX:Configuration:InvalidBoolean', '%s must be true or false.', name);
        output.(key) = logical(value);
    else
        allowAuto = isscalar(original) && (isnan(double(original)) || ...
            contains(key, 'Override') || strcmp(key, 'EffectiveInductance_H'));
        legacyAuto = (ischar(value) || (isstring(value) && isscalar(value))) && ...
            any(strcmpi(strtrim(value), {'auto', 'null', 'nan', '自动'}));
        if allowAuto && (isempty(value) || legacyAuto)
            value = NaN;
        end
        assert(isnumeric(value) && isreal(value) && numel(value) == numel(original), ...
            'YMBOX:Configuration:InvalidNumber', '%s has an invalid numeric shape.', name);
        assert(all(isfinite(value(:))) || (allowAuto && isscalar(value) && isnan(value)), ...
            'YMBOX:Configuration:Nonfinite', '%s must be finite or an allowed automatic value.', name);
        if isinteger(original)
            assert(all(value(:) == fix(value(:))) && ...
                all(value(:) >= double(intmin(class(original)))) && ...
                all(value(:) <= double(intmax(class(original)))), ...
                'YMBOX:Configuration:IntegerRange', '%s is outside its integer range.', name);
        end
        typedValue = cast(value, class(original));
        if isa(original, 'single') && all(isfinite(value(:)))
            assert(all(isfinite(typedValue(:))) && ...
                all(value(:) == 0 | typedValue(:) ~= 0), ...
                'YMBOX:Configuration:SingleRange', ...
                '%s cannot be represented by the model single data type.', name);
        end
        output.(key) = reshape(typedValue, size(original));
    end
end
end

function validateExecution(cfg)
ex = cfg.Execution;
assert(ismember(ex.ObserverBuildVariant, uint8([0 1])), ...
    'YMBOX:Configuration:ObserverVariant', 'Observer build must be 0 or 1.');
assert(ismember(ex.WorkMode_enum, uint16(0:6)), ...
    'YMBOX:Configuration:WorkMode', 'Work mode must be a public mode from 0 to 6.');
assert(ex.ObserverBuildVariant == 1 || ex.WorkMode_enum ~= 6, ...
    'YMBOX:Configuration:UnsupportedMode', 'Mode 6 requires the SMO build.');
assert(ex.StopTime_s > 0 && abs(ex.TargetSpeed_rpm) <= cfg.Limits.SpeedCommandAbsMax_rpm, ...
    'YMBOX:Configuration:SimulationCommand', 'Invalid simulation duration or speed command.');
assert(cfg.Motor.StatorResistance_Ohm > 0 && cfg.Motor.Inertia_kgm2 > 0 && ...
    cfg.Motor.PolePairs == fix(cfg.Motor.PolePairs), ...
    'YMBOX:Configuration:Motor', 'Motor resistance/inertia must be positive and pole pairs integral.');
assert(cfg.Inverter.MinValidDcBus_V > 0 && ...
    cfg.Inverter.MinValidDcBus_V < cfg.Inverter.NominalDcBus_V && ...
    cfg.Inverter.NominalDcBus_V < cfg.Inverter.MaxDcBus_V, ...
    'YMBOX:Configuration:VoltageRange', 'Require minimum < nominal < maximum DC-bus voltage.');
assert(isequal(cfg.Meta.ControlAngleConvention, 'electrical_positive_q'), ...
    'YMBOX:Configuration:FixedContract', 'The model angle convention cannot be changed.');
assert(~cfg.Features.SensorlessFieldWeakeningEnable && ~cfg.FieldWeakening.SensorlessEnable, ...
    'YMBOX:Configuration:ReleaseGate', 'Sensorless field weakening is not enabled by this tool.');
assert(cfg.Features.ActiveInverterCompensationEnable == cfg.Inverter.ActiveNonlinearityCompensationEnable && ...
    cfg.Features.SensoredFieldWeakeningEnable == cfg.FieldWeakening.Enable, ...
    'YMBOX:Configuration:FeatureMismatch', 'Feature flags and their owned settings must agree.');
p = cfg.Protection;
ov = p.DcBusOverVoltage_V;
uv = p.DcBusUnderVoltage_V;
if isnan(ov), ov = min(cfg.Inverter.MaxDcBus_V, 1.2*cfg.Inverter.NominalDcBus_V); end
if isnan(uv), uv = 0.5*cfg.Inverter.NominalDcBus_V; end
assert(uv >= 0 && uv < cfg.Inverter.NominalDcBus_V && ...
    ov > cfg.Inverter.NominalDcBus_V && ov <= cfg.Inverter.MaxDcBus_V, ...
    'YMBOX:Configuration:ProtectionVoltage', 'Protection voltage thresholds are inconsistent.');
assert((isnan(p.VoltageViolationArea_Vs) || p.VoltageViolationArea_Vs > 0) && ...
    p.VoltageRecoveryRate_V >= 0 && p.VoltageRecoveryRate_V <= 100 && ...
    p.FaultClearHold_s >= 0 && p.FaultClearHold_s <= 60 && ...
    p.CommandTimeout_s >= 0.001 && p.CommandTimeout_s <= 10, ...
    'YMBOX:Configuration:ProtectionTiming', 'Invalid protection qualification settings.');
assert(ismember(cfg.Feedforward.VoltageMode_enum, uint8(0:3)), ...
    'YMBOX:Configuration:FeedforwardMode', 'Voltage feedforward mode must be 0, 1, 2 or 3.');
assert(all([cfg.Feedforward.DAxisScale_NULL cfg.Feedforward.QAxisScale_NULL] >= 0) && ...
    all([cfg.Feedforward.DAxisScale_NULL cfg.Feedforward.QAxisScale_NULL] <= 1) && ...
    cfg.Feedforward.ElectricalAngleCompScale_NULL >= 0 && ...
    cfg.Feedforward.ElectricalAngleCompScale_NULL <= 1.5, ...
    'YMBOX:Configuration:Feedforward', 'Feedforward scale is outside its supported range.');
end
